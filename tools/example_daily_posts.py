def scrim(img,box,amt=110):
    """soft local darkening behind text (no hard black band)"""
    m=Image.new('L',(W//4,H//4),0); d=ImageDraw.Draw(m); x0,y0,x1,y1=[v//4 for v in box]
    d.rounded_rectangle([x0,y0,x1,y1],radius=30,fill=amt); m=m.filter(ImageFilter.GaussianBlur(28)).resize((W,H))
    img.alpha_composite(Image.merge('RGBA',(*Image.new('RGB',(W,H),(6,9,9)).split(),m)))
def fade_bottom(img):
    g=Image.new('L',(1,H))
    for y in range(H): g.putpixel((0,y),int(255*min(1,max(0,(y-H*.84)/(H*.16))**1.3*.6)))
    img.alpha_composite(Image.merge('RGBA',(*Image.new('RGB',(W,H),(8,10,10)).split(),g.resize((W,H)))))
